import type { Note } from "./material.ts";

const labIndex = "Фронтенд/Практикумы/00. Карта раздела";
const overviewIds = new Set(
  ["Фронтенд/00. Карта раздела", "Фронтенд/Внешние материалы"].flatMap((id) => [
    id,
    `bundled-rounds/${id}`,
  ]),
);
const normalize = (markdown: string) =>
  markdown
    .replace(/^\uFEFF/, "")
    .replace(/\r\n/g, "\n")
    .trim();

// This projection is used only by the library list. The full catalog retains
// every ID and scoped revision for direct URLs and links inside other notes.
export function libraryNotes(notes: Note[], originals: Note[] = notes): Note[] {
  const current = notes.find(
    (note) => note.id === `bundled-rounds/${labIndex}`,
  );
  const originalById = new Map(originals.map((note) => [note.id, note]));
  const text = (note: Note) =>
    normalize((originalById.get(note.id) || note).markdown);
  return notes
    .filter(
      (note) =>
        !overviewIds.has(note.id) &&
        !(
          current &&
          note.id === labIndex &&
          [
            legacyLabIndex,
            legacyDownloadableLabIndex,
            text(current),
            text(current).replaceAll("Prep Lab", "Frontend Lab"),
          ].includes(text(note))
        ),
    )
    .map((note) => {
      if (
        note.id === current?.id ||
        (!current && note.id === labIndex && note.title === "Практикумы")
      )
        return { ...note, title: "Стенды и упражнения" };
      return note;
    });
}

